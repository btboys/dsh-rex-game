import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'

/**
 * Score store shared by the plugin's Host route (same-origin fallback) and the
 * standalone `server/leaderboard.mjs` service deployed on dsh.gson.cn.
 *
 * Identity model: the first time a device talks to the board it registers its
 * locally generated device code; the server assigns the next user number
 * (1, 2, 3, ...) and signs it. The number never changes for that device code,
 * and the score submission carries a server-issued run token, so a client can
 * neither pick its own number nor post a score it did not play:
 *
 *   POST <base>/register {device}        -> { user: { id, name }, token }
 *   POST <base>/start {token}            -> { run }
 *   GET  <base>/scores                   -> { scores }
 *   POST <base>/scores {run, score}      -> { scores }
 *
 * A manual caller can still wait out a run and submit a maximal score, but it
 * cannot choose a user number, impersonate another device, replay a run, or
 * backfill a forged history.
 */
export const MAX_ENTRIES = 20
export const MAX_SCORE = 9_999_999
export const MAX_NAME = 16
const MAX_BODY = 4096
const RATE_WINDOW_MS = 60_000
const RATE_MAX_POSTS = 20
const RATE_MAX_STARTS = 40
const RATE_MAX_REGISTRATIONS = 20
const RUN_TTL_MS = 15 * 60_000
// The game awards `speed * 0.06` points per second and caps speed at 320 px/s,
// so 19.2 points/s is the physical ceiling; keep a small margin for rounding.
const MAX_SCORE_RATE = 22
const SCORE_GRACE = 60

export function defaultDataFile(home = process.env.DSH_HOME ?? join(homedir(), '.dsh')) {
  return join(home, 'plugin-data', 'dsh-whale-break', 'scores.json')
}

function usersFile(file) {
  return join(dirname(file), 'users.json')
}

function normalizeName(value) {
  if (typeof value !== 'string') return ''
  return value
    .replace(/[\u0000-\u001f\u007f]/gu, '')
    .trim()
    .slice(0, MAX_NAME)
}

/** The display name is derived from the server-owned number only. */
export function userName(id) {
  return `小鲸鱼${id}`
}

/** Device codes are generated by the browser: 8-64 URL-safe characters. */
export function normalizeDevice(value) {
  if (typeof value !== 'string') return undefined
  return /^[A-Za-z0-9_-]{8,64}$/u.test(value) ? value : undefined
}

/** Accept only a bounded integer score; the name and user number are server-owned. */
export function normalizeScore(value) {
  const score = Math.floor(Number(value))
  if (!Number.isFinite(score) || score < 0 || score > MAX_SCORE) return undefined
  return score
}

/** Keep the board descending; ties keep the older entry first. One row per user, best score wins. */
export function mergeEntries(entries, entry) {
  if (entry.uid === undefined) {
    return [...entries, entry].sort((a, b) => b.score - a.score || a.at - b.at).slice(0, MAX_ENTRIES)
  }
  const previous = entries.find((item) => item.uid === entry.uid)
  const best = previous !== undefined && previous.score > entry.score ? previous : entry
  const rest = entries.filter((item) => item.uid !== entry.uid)
  return [...rest, best].sort((a, b) => b.score - a.score || a.at - b.at).slice(0, MAX_ENTRIES)
}

function sanitizeStored(item) {
  if (item === null || typeof item !== 'object') return undefined
  const score = normalizeScore(item.score)
  if (score === undefined) return undefined
  return {
    uid: Number.isInteger(item.uid) && item.uid > 0 ? item.uid : undefined,
    name: normalizeName(item.name) || '匿名鲸鱼',
    score,
    at: typeof item.at === 'number' && Number.isFinite(item.at) ? item.at : 0,
  }
}

export async function readEntries(file) {
  try {
    const parsed = JSON.parse(await readFile(file, 'utf8'))
    if (!Array.isArray(parsed)) return []
    return parsed
      .map(sanitizeStored)
      .filter((entry) => entry !== undefined)
      .sort((a, b) => b.score - a.score || a.at - b.at)
      .slice(0, MAX_ENTRIES)
  } catch (_error) {
    return []
  }
}

function atomicWrite(file, data) {
  return mkdir(dirname(file), { recursive: true }).then(async () => {
    const temp = `${file}.${process.pid}.${Date.now()}.tmp`
    await writeFile(temp, data)
    await rename(temp, file)
  })
}

// Writes are serialized so two concurrent posts cannot drop one another.
let writing = Promise.resolve()

export async function addEntry(entry, file) {
  const run = async () => {
    const entries = mergeEntries(await readEntries(file), entry)
    await atomicWrite(file, JSON.stringify(entries))
    return entries
  }
  const next = writing.then(run, run)
  writing = next.catch(() => {})
  return next
}

// ---------------------------------------------------------------- identities

const DEVICE_FALLBACK_ID = 1

export async function readUsers(file) {
  try {
    const raw = JSON.parse(await readFile(usersFile(file), 'utf8'))
    if (raw !== null && typeof raw === 'object' && raw.byDevice !== null && typeof raw.byDevice === 'object') {
      const nextId = Number.isInteger(raw.nextId) && raw.nextId > 0 ? raw.nextId : DEVICE_FALLBACK_ID
      return { nextId, byDevice: raw.byDevice }
    }
  } catch (_error) {}
  return { nextId: DEVICE_FALLBACK_ID, byDevice: {} }
}

async function writeUsers(state, file) {
  await atomicWrite(usersFile(file), JSON.stringify(state))
}

let usersWriting = Promise.resolve()

/**
 * Register a device code and return its stable user. User numbers start at 1
 * and are handed out in registration order; re-registering the same device is
 * idempotent.
 */
export async function registerDevice(device, file) {
  const operation = async () => {
    const state = await readUsers(file)
    const existing = state.byDevice[device]
    if (existing !== undefined && Number.isInteger(existing.id)) return existing
    const id = state.nextId
    const user = { id, name: `用户${id}` }
    state.byDevice[device] = user
    state.nextId = id + 1
    await writeUsers(state, file)
    return user
  }
  const next = usersWriting.then(operation, operation)
  usersWriting = next.catch(() => {})
  return next
}

async function findUser(file, uid) {
  const state = await readUsers(file)
  for (const user of Object.values(state.byDevice)) {
    if (user?.id === uid) return user
  }
  return undefined
}

// ---------------------------------------------------------------- signed tokens

const secrets = new Map()

async function secretFor(file) {
  if (process.env.SCOREBOARD_SECRET) return process.env.SCOREBOARD_SECRET
  const cached = secrets.get(file)
  if (cached !== undefined) return cached
  const path = join(dirname(file), 'secret')
  let secret
  try {
    secret = (await readFile(path, 'utf8')).trim()
  } catch (_error) {
    secret = randomBytes(32).toString('hex')
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, secret, { mode: 0o600 })
  }
  secrets.set(file, secret)
  return secret
}

function sign(secret, body) {
  return createHmac('sha256', secret).update(body).digest('base64url')
}

async function signPayload(payload, file) {
  const secret = await secretFor(file)
  const body = Buffer.from(JSON.stringify(payload)).toString('base64url')
  return `${body}.${sign(secret, body)}`
}

async function verifyPayload(token, file) {
  if (typeof token !== 'string') return undefined
  const [body, mac] = token.split('.')
  if (body === undefined || mac === undefined) return undefined
  const secret = await secretFor(file)
  const expected = sign(secret, body)
  if (mac.length !== expected.length) return undefined
  if (!timingSafeEqual(Buffer.from(mac), Buffer.from(expected))) return undefined
  try {
    return JSON.parse(Buffer.from(body, 'base64url').toString('utf8'))
  } catch (_error) {
    return undefined
  }
}

/** A long-lived identity token binding a user number to its device code. */
export async function issueIdentity(user, device, file) {
  return signPayload({ kind: 'id', uid: user.id, device }, file)
}

/** @returns the user record for a valid identity token, or `undefined`. */
export async function resolveIdentity(token, file) {
  const payload = await verifyPayload(token, file)
  if (payload?.kind !== 'id' || !Number.isInteger(payload.uid) || typeof payload.device !== 'string') {
    return undefined
  }
  const state = await readUsers(file)
  const user = state.byDevice[payload.device]
  if (user === undefined || user.id !== payload.uid) return undefined
  return user
}

/** Run tokens are single-use and bound to the user who started them. */
export async function issueRun(user, file) {
  return signPayload({ kind: 'run', id: randomBytes(12).toString('base64url'), iat: Date.now(), uid: user.id }, file)
}

const usedRuns = new Map()

function pruneUsed(now = Date.now()) {
  for (const [id, expiresAt] of usedRuns) if (expiresAt <= now) usedRuns.delete(id)
}

/** @returns `{ elapsedMs, uid }` for a fresh run token, or `undefined`. */
export async function consumeRun(token, file) {
  const payload = await verifyPayload(token, file)
  if (payload?.kind !== 'run' || typeof payload.id !== 'string' || typeof payload.iat !== 'number') return undefined
  if (!Number.isInteger(payload.uid)) return undefined
  const now = Date.now()
  const elapsedMs = now - payload.iat
  if (elapsedMs < 0 || elapsedMs > RUN_TTL_MS) return undefined
  pruneUsed(now)
  if (usedRuns.has(payload.id)) return undefined
  usedRuns.set(payload.id, payload.iat + RUN_TTL_MS)
  return { elapsedMs, uid: payload.uid }
}

/** The largest score the game could have produced in `elapsedMs`. */
export function maxScoreFor(elapsedMs) {
  const elapsed = Math.max(0, elapsedMs) / 1000
  return Math.min(MAX_SCORE, Math.floor(elapsed * MAX_SCORE_RATE) + SCORE_GRACE)
}

// ---------------------------------------------------------------- HTTP face

const hits = new Map()

/**
 * Real client address: behind nginx/uuwaf the socket belongs to the proxy, so
 * the left-most X-Forwarded-For hop is used when present. A client can forge
 * that header to dodge its own throttle, which is an acceptable trade for a
 * toy board; scores still need a valid run token.
 */
function clientIp(request) {
  const forwarded = request.headers?.['x-forwarded-for']
  if (typeof forwarded === 'string') {
    const first = forwarded.split(',')[0]?.trim()
    if (first) return first
  }
  const realIp = request.headers?.['x-real-ip']
  if (typeof realIp === 'string' && realIp.trim()) return realIp.trim()
  return request.socket?.remoteAddress ?? 'unknown'
}

/** Cheap per-IP throttle; the board is a toy, not a target. */
function allowPost(key, limit = RATE_MAX_POSTS) {
  const now = Date.now()
  const recent = (hits.get(key) ?? []).filter((at) => now - at < RATE_WINDOW_MS)
  if (recent.length >= limit) {
    hits.set(key, recent)
    return false
  }
  recent.push(now)
  hits.set(key, recent)
  if (hits.size > 5000) hits.clear()
  return true
}

function send(response, status, body) {
  response.writeHead(status, CORS_HEADERS)
  response.end(JSON.stringify(body))
}

function readJson(request) {
  return new Promise((resolve, reject) => {
    const chunks = []
    let size = 0
    request.on('data', (chunk) => {
      size += chunk.length
      if (size > MAX_BODY) {
        reject(new Error('body too large'))
        request.destroy()
        return
      }
      chunks.push(chunk)
    })
    request.on('end', () => {
      try {
        resolve(JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}'))
      } catch (error) {
        reject(error)
      }
    })
    request.on('error', reject)
  })
}

export const CORS_HEADERS = Object.freeze({
  'content-type': 'application/json; charset=utf-8',
  'cache-control': 'no-store',
  'access-control-allow-origin': '*',
  'access-control-allow-methods': 'GET,POST,OPTIONS',
  'access-control-allow-headers': 'content-type',
})

/**
 * A Node `http` request handler for one scoreboard base path.
 * @returns `{ kind: 'prefix', path, handler }`, registerable on `ctx.webServer`.
 */
export function createScoreRoute({ file = defaultDataFile(), path = '/dsh-whale-break' } = {}) {
  const handler = async (request, response) => {
    try {
      if (request.method === 'OPTIONS') {
        response.writeHead(204, CORS_HEADERS)
        response.end()
        return
      }
      const pathname = new URL(request.url ?? '/', 'http://local').pathname
      const ip = clientIp(request)
      if (request.method !== 'OPTIONS') console.log(`${request.method} ${pathname} ${ip}`)
      const isRegister = pathname.endsWith('/register')
      const isStart = pathname.endsWith('/start')
      const isScores = pathname.endsWith('/scores')
      if (!isRegister && !isStart && !isScores) {
        send(response, 404, { error: 'not found' })
        return
      }

      if (isRegister && request.method === 'POST') {
        if (!allowPost(ip, RATE_MAX_REGISTRATIONS)) {
          send(response, 429, { error: 'too many registrations' })
          return
        }
        const device = normalizeDevice((await readJson(request)).device)
        if (device === undefined) {
          send(response, 400, { error: 'invalid device code' })
          return
        }
        const user = await registerDevice(device, file)
        const token = await issueIdentity(user, device, file)
        send(response, 200, { user: { id: user.id, name: userName(user.id) }, token })
        return
      }

      if (isStart && request.method === 'POST') {
        if (!allowPost(ip, RATE_MAX_STARTS)) {
          send(response, 429, { error: 'too many runs' })
          return
        }
        const user = await resolveIdentity((await readJson(request)).token, file)
        if (user === undefined) {
          send(response, 401, { error: 'device registration required' })
          return
        }
        send(response, 200, { run: await issueRun(user, file) })
        return
      }

      if (isScores && request.method === 'GET') {
        send(response, 200, { scores: await readEntries(file) })
        return
      }

      if (isScores && request.method === 'POST') {
        if (!allowPost(ip)) {
          send(response, 429, { error: 'too many scores' })
          return
        }
        const body = await readJson(request)
        const score = normalizeScore(body.score)
        if (score === undefined) {
          send(response, 400, { error: 'invalid score' })
          return
        }
        const run = await consumeRun(body.run, file)
        if (run === undefined) {
          send(response, 401, { error: 'run token required' })
          return
        }
        if (score > maxScoreFor(run.elapsedMs)) {
          send(response, 400, { error: 'score exceeds the run duration' })
          return
        }
        const user = await findUser(file, run.uid)
        if (user === undefined) {
          send(response, 401, { error: 'unknown user' })
          return
        }
        const entry = { uid: user.id, name: userName(user.id), score, at: Date.now() }
        send(response, 200, { scores: await addEntry(entry, file) })
        return
      }

      response.writeHead(405, { ...CORS_HEADERS, allow: 'GET,POST,OPTIONS' })
      response.end()
    } catch (_error) {
      send(response, 500, { error: 'scoreboard failed' })
    }
  }
  return { kind: 'prefix', path, handler }
}
